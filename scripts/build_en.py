def load(src):
    if src.startswith('http'):
        with urllib.request.urlopen(src) as r:
            return json.load(r)
    return json.loads(Path(src).read_text(encoding='utf-8'))


def build(raw):
    missing = set()
    def tr(table, key):
        if key not in table:
            missing.add(key)
        return table.get(key, key)
    out = [{
        'id': it['id'],
        'system': tr(SYSTEM, it['系統']),
        'number': it['ポーズ番号'],
        'category': tr(CATEGORY, it['分類']),
        'name': tr(POSE, it['ポーズ名']),
        'angle': tr(ANGLE, it['アングル']),
        'thumb': IMG_BASE + it['サムネ'],
        'full': IMG_BASE + it['原寸'],
    } for it in raw]
    return out, missing


